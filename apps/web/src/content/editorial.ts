export function findEditorialPage(slug: string): EditorialPage | undefined {
  return [...guides, ...articles].find((item) => item.slug === slug);
}

export function findSubject(slug: string): SubjectPage | undefined {
  const subject = subjects.find((item) => item.slug === slug);
  if (!subject) return undefined;
  return {
    ...subject,
    syllabus: subject.syllabus ?? syllabusBySubject[subject.slug] ?? [],
    syllabusSource: subject.syllabusSource ?? syllabusSourceBySubject[subject.slug] ?? syllabSource,
  };
}

export function editorialDateIso(value: string): string {
  const normalized = value.replace(/[۰-۹]/g, (digit) => String("۰۱۲۳۴۵۶۷۸۹".indexOf(digit)));
  const match = normalized.match(/^1405-06-(\d{1,2})$/);
  if (!match) return value;
  // 1 Shahrivar 1405 is 23 August 2026. Date.UTC safely rolls into September.
  return new Date(Date.UTC(2026, 7, 22 + Number(match[1]))).toISOString().slice(0, 10);
}
