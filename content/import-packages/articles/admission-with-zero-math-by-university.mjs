const wl = U.reduce((s, [, v]) => s + v.zeroLang * v.n, 0) / total;
const hi = U[0], lo = U[U.length - 1];
const g = (k) => S[k];
const byGpa = [...U].sort((a, b) => b[1].gpa.med - a[1].gpa.med);
